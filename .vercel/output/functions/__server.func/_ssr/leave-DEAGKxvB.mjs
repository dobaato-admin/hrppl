function daysBetween(start, end, halfStart, halfEnd) {
  const s = /* @__PURE__ */ new Date(start + "T00:00:00Z");
  const e = /* @__PURE__ */ new Date(end + "T00:00:00Z");
  if (e < s) return 0;
  const diff = Math.round((e.getTime() - s.getTime()) / (1e3 * 60 * 60 * 24)) + 1;
  let d = diff;
  if (halfStart) d -= 0.5;
  if (halfEnd && start !== end) d -= 0.5;
  return Math.max(0.5, d);
}
