async function downloadArticlePdf(article) {
  try {
    const {
      jsPDF
    } = await import("../_libs/jspdf.mjs").then(function(n) {
      return n.j;
    });
    const doc = new jsPDF({
      unit: "pt",
      format: "a4"
    });
    const pageW = doc.internal.pageSize.getWidth();
    const pageH = doc.internal.pageSize.getHeight();
    const margin = 48;
    const maxW = pageW - margin * 2;
    let y = margin;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(20);
    doc.text(doc.splitTextToSize(article.title, maxW), margin, y);
    y += 28;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(110);
    doc.text(`${article.category.toUpperCase()}  •  Updated ${new Date(article.updated_at).toLocaleDateString()}`, margin, y);
    y += 14;
    if (article.summary) {
      doc.setFontSize(11);
      doc.setTextColor(60);
      const lines = doc.splitTextToSize(article.summary, maxW);
      doc.text(lines, margin, y);
      y += lines.length * 14 + 6;
    }
    doc.setDrawColor(220);
    doc.line(margin, y, pageW - margin, y);
    y += 14;
    doc.setTextColor(20);
    const blocks = article.body_md.split(/\n\n+/);
    for (const raw of blocks) {
      const block = raw.replace(/\r/g, "");
      const ensure = (h) => {
        if (y + h > pageH - margin) {
          doc.addPage();
          y = margin;
        }
      };
      if (/^#\s/.test(block)) {
        doc.setFont("helvetica", "bold");
        doc.setFontSize(16);
        const t = block.replace(/^#\s+/, "");
        const ls = doc.splitTextToSize(t, maxW);
        ensure(ls.length * 20);
        doc.text(ls, margin, y);
        y += ls.length * 20 + 6;
      } else if (/^##\s/.test(block)) {
        doc.setFont("helvetica", "bold");
        doc.setFontSize(13);
        const t = block.replace(/^##\s+/, "");
        const ls = doc.splitTextToSize(t, maxW);
        ensure(ls.length * 16);
        doc.text(ls, margin, y);
        y += ls.length * 16 + 4;
      } else if (/^###\s/.test(block)) {
        doc.setFont("helvetica", "bold");
        doc.setFontSize(11);
        const t = block.replace(/^###\s+/, "");
        const ls = doc.splitTextToSize(t, maxW);
        ensure(ls.length * 14);
        doc.text(ls, margin, y);
        y += ls.length * 14 + 4;
      } else if (/^[-*]\s/m.test(block)) {
        doc.setFont("helvetica", "normal");
        doc.setFontSize(10.5);
        for (const item of block.split(/\n/)) {
          const t = item.replace(/^[-*]\s+/, "").replace(/^\d+\.\s+/, "");
          if (!t.trim()) continue;
          const ls = doc.splitTextToSize("• " + stripInline(t), maxW - 12);
          ensure(ls.length * 13);
          doc.text(ls, margin + 12, y);
          y += ls.length * 13 + 2;
        }
        y += 4;
      } else if (/^>/.test(block)) {
        doc.setFont("helvetica", "italic");
        doc.setFontSize(10.5);
        doc.setTextColor(90);
        const t = block.replace(/^>\s?/gm, "");
        const ls = doc.splitTextToSize(stripInline(t), maxW - 16);
        ensure(ls.length * 13 + 8);
        doc.setDrawColor(180);
        doc.line(margin, y - 8, margin, y + ls.length * 13);
        doc.text(ls, margin + 12, y);
        y += ls.length * 13 + 8;
        doc.setTextColor(20);
      } else if (/^---+$/.test(block.trim())) {
        ensure(14);
        doc.setDrawColor(220);
        doc.line(margin, y, pageW - margin, y);
        y += 14;
      } else {
        doc.setFont("helvetica", "normal");
        doc.setFontSize(10.5);
        const ls = doc.splitTextToSize(stripInline(block.replace(/\n/g, " ")), maxW);
        ensure(ls.length * 13);
        doc.text(ls, margin, y);
        y += ls.length * 13 + 6;
      }
    }
    const pages = doc.getNumberOfPages();
    for (let i = 1; i <= pages; i++) {
      doc.setPage(i);
      doc.setFontSize(8);
      doc.setTextColor(140);
      doc.text(`hrppl — ${article.title}  •  Page ${i} of ${pages}`, margin, pageH - 20);
    }
    doc.save(`${article.slug}.pdf`);
  } catch (e) {
    toast.error(e.message ?? "Couldn't build PDF");
  }
}
function stripInline(s) {
  return s.replace(/\*\*(.+?)\*\*/g, "$1").replace(/\*(.+?)\*/g, "$1").replace(/`(.+?)`/g, "$1").replace(/\[(.+?)\]\((.+?)\)/g, "$1 ($2)");
}
