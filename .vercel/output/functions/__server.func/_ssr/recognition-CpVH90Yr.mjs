function useColleagues() {
  const directoryFn = useServerFn(getCompanyDirectory);
  const meFn = useServerFn(myEmployeeId);
  const {
    data
  } = useQuery({
    queryKey: ["recognition-colleagues"],
    queryFn: async () => {
      const [dir, me] = await Promise.all([directoryFn({
        data: {
          limit: 200
        }
      }), meFn()]);
      const mine = me?.employee?.id;
      return (dir.employees ?? []).filter((e) => e.id !== mine);
    },
    staleTime: 5 * 6e4
  });
  return data ?? [];
}
