function fmtMoney(amount, currency) {
  try {
    return new Intl.NumberFormat(void 0, {
      style: "currency",
      currency,
      maximumFractionDigits: 0
    }).format(amount);
  } catch {
    return `${currency} ${amount}`;
  }
}
function fmtDate(d) {
  if (!d) return "—";
  try {
    return new Date(d).toLocaleDateString(void 0, {
      dateStyle: "medium"
    });
  } catch {
    return d;
  }
}
